#' Reads the OD measurements from the plate readers .txt output file
#'
#' Extracts 384-well measurements and returns one table per measurement, one for each strain
#' Duplicate strains get unique identifiers
#'
#' @param path Character string giving the path to the raw text file
#' @return A named list of numeric data frames, each with rows A-P
#'   and columns 1-24
#' @export
od_plate_reader <- function(path) {

  # 1. Reading the file
  #Each line of the text file is read separately and gets put into character vector
  #this is needed because the raw data is not in a data frame format so it's tricky to read
  lines <- read_lines(path)

  # 2. Finding the measurements
  #all different measurements start with "Field Group", algorithm looks for this
  #the 'start_lines' variable stores the line numbers of where the data starts for all strains measured
  #including the 'Plate ID' that names the bacterial strain
  #regex generated by AI. since I don't speak that language very well :p
  start_lines <- which(str_detect(lines, regex("^\\s*Field\\s+Group\\s*$", ignore_case = TRUE)))

  #the end of all the data blocks is simpler
  #they all end 1 line before the next begins
  #this way the end line is always the start line minus 1
  #-1 vector index ignores the first start line, as that is line 1, there is no data before it :p
  #the it extracts 1 from each stats line to mark the previous sections' end line
  end_lines <- c(start_lines[-1] - 1, length(lines))


  # 3. separating each measurement block
  #map2() applies the created local funtion to its 2 values (start and end number)
  #not a fan of purrr functions, but it does the job....
  #also contains a huge code chunk
  measurements <- map2(
    .x = start_lines,
    .y = end_lines,
    .f = function(start, end) {

      block <- lines[start:end]

      #failure function for error messages
      #not my own idea
      #stops the function fro working and reports the location
      fail <- function(message) {
        stop(
          paste0("Block beginning at line ", start, ": ", message),
          call. = FALSE
        )
      }


      # 4. extracting the strain names
      #regex finds the lines that contains 'Plate ID'
      id_pattern <- regex("^\\s*Plate\\s+ID\\s*:\\s*", ignore_case = TRUE)

      #returns the number of the line that has the plate id aka. the strain name
      id_line <- block[str_detect(block, id_pattern)]

      #getting the strain name
      #removing the label and the white space
      #thank you stringR for the useful functions
      strain <- id_line |>
        str_remove(id_pattern) |>
        str_trim()


      # 5. extracting the plate rows
      #keep only the lines that start with a letter [A-P] followed by a tab
      #these lines mark the actual lines of data
      data_rows <- block[str_detect(block, "^\\s*[A-P]\\t")]

      #split all the data at the tabs
      #splits the lines of data into individual measurements
      #map applies a white-space trim too all created values
      fields <- str_split(data_rows, fixed("\t")) |>
        map(str_trim)


      # 6. Checking the plate structure for any errors
      #proved surprisingly useful during testing
      #a 'correct' plate must have 16 rows [A-P]
      #a 'correct' row must have 26(!) fields:
      #   1 row label [A-P], 24 OD values + 1 Wavelength value
      if (length(fields) != 16L || any(lengths(fields) != 26L)) {
        fail("Expected 16 rows, each with 24 OD cells and a wavelength.")
      }

      # 7. Building the actual OD table
      #keeping only column 1-25 (row label + 24 measurements)
      #26th row is ignore (wavelenght tracker)
      #each row becomes a separate 1-row tall tibble
      #map_dfr the combines them into a single data frame
      plate <- map_dfr(fields, function(x) {
        as_tibble_row(set_names(x[1:25], c("row", as.character(1:24))))
      })

      #8. converts the OD values from text to numbers
      #applies parse_double to ever column Except the row labels (-row)
      #empty cell become NA
      plate <- plate |>
        mutate(across(-row, ~ parse_double(.x, na = c("", "NA"))))


      # 9. Assigning the row names
      #turns the 'row' column into actual row names
      plate <- plate |>
        column_to_rownames("row")

      #returns the strain name and its table
      list(strain = strain, plate = plate)


    }) #closing the map2 and the included functions

  # 10. Naming the tables
  #repeated measurements of the same strain are marked with _1 and _2
  table_names <- tibble(
    strain = map_chr(measurements, "strain")) |>
    group_by(strain) |>
    mutate(table_name = if (n() > 1L) {
      str_c(strain, "_", row_number())
    } else {strain
    }) |>
    ungroup() |>
    pull(table_name)

  #return the different table as a named list
  measurements |>
    map("plate") |>
    set_names(table_names)

}
